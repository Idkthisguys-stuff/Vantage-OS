import argparse
import os
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]


def tool_dirs(root):
    if not root:
        return []
    root = Path(root).expanduser()
    return [root, root / 'bin', *sorted(root.glob('xpack-windows-build-tools-*/bin'))]


def find_tool(name, directories, path):
    return shutil.which(name, path=os.pathsep.join([*(str(p) for p in directories), path]))


def parser():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('target', nargs='?', choices=('kernel', 'sim', 'test'), default='kernel')
    p.add_argument('--toolchain-dir', default=os.environ.get('VANTAGE_TOOLCHAIN_DIR'),
                   help='portable GNU tools root (or set VANTAGE_TOOLCHAIN_DIR)')
    p.add_argument('--sdl', help='SDL2 CMake package prefix for sim')
    p.add_argument('--build-dir', help='output directory')
    p.add_argument('--make', help='GNU make executable')
    p.add_argument('--prefix', help='cross-tool prefix, e.g. aarch64-none-elf-')
    p.add_argument('--jobs', type=int, default=max(1, os.cpu_count() or 1))
    p.add_argument('--v3d', choices=('0', '1'))
    p.add_argument('--wifi', choices=('0', '1'))
    p.add_argument('--ethernet', choices=('0', '1'))
    p.add_argument('--storage', choices=('0', '1'))
    p.add_argument('--storage-validation', choices=('0', '1'))
    p.add_argument('--sd-base-clock-hz', type=int)
    p.add_argument('--storage-partition', type=int, choices=range(4))
    p.add_argument('--wifi-firmware-c', help='C file generated by tools/embed_wifi.py')
    p.add_argument('--wifi-country', default=os.environ.get('VANTAGE_WIFI_COUNTRY'),
                   help='two-letter country where the Pi is used, or auto to look it up again '
                        '(or set VANTAGE_WIFI_COUNTRY; default: remembered or looked up from the IP '
                        'address); see tools/fetch_wifi.py')
    p.add_argument('--wifi-regrev', type=int, help='regulatory revision for the Wi-Fi country (default -1)')
    p.add_argument('--tls-trust-c', help='TLS trust anchor C file from tools/fetch_ca.py, or none (or set '
                                         'TLS_TRUST_C; default: download and convert the pinned Mozilla CA bundle)')
    return p


def wifi_assets(country, regrev, fail=None):
    """Download and embed the Wi-Fi firmware, accepting its license. Returns the
    generated C file. Failures call fail, or return None when fail is None."""
    sys.path.insert(0, str(ROOT / 'tools'))
    import fetch_wifi
    try:
        code, origin = fetch_wifi.resolve_country(country)
        print(f'Wi-Fi country: {code} ({origin}; change it with --wifi-country)', flush=True)
        return fetch_wifi.prepare(code, regrev, accepted=True)
    except fetch_wifi.FirmwareError as error:
        if fail:
            fail(str(error))
        print(f'Wi-Fi firmware unavailable: {error}', file=sys.stderr, flush=True)
        return None


def tls_trust():
    """Download and convert the pinned CA bundle. Returns the generated C file,
    or None after a warning: the kernel then builds without trust anchors."""
    sys.path.insert(0, str(ROOT / 'tools'))
    import fetch_ca
    try:
        return fetch_ca.prepare()
    except (fetch_ca.BundleError, OSError) as error:
        print(f'TLS trust anchors unavailable: {error}', file=sys.stderr, flush=True)
        return None


def run(command, env):
    print('+', subprocess.list2cmdline([str(x) for x in command]), flush=True)
    subprocess.run([str(x) for x in command], cwd=ROOT, env=env, check=True)


def main(argv=None):
    p = parser()
    a = p.parse_args(argv)
    if a.jobs < 1:
        p.error('--jobs must be positive')
    if a.sd_base_clock_hz is not None and not 400000 <= a.sd_base_clock_hz <= 818400000:
        p.error('--sd-base-clock-hz must be between 400000 and 818400000')
    env = os.environ.copy()
    explicit_country = any(arg == '--wifi-country' or arg.startswith('--wifi-country=')
                           for arg in (sys.argv[1:] if argv is None else argv))
    wifi_off = (a.wifi or env.get('WIFI')) == '0'
    fetch = not (a.target != 'kernel' or wifi_off or a.wifi_firmware_c or
                 (env.get('WIFI_FIRMWARE_C') and not explicit_country))
    if not fetch:
        # Only an explicit option conflicts; the environment default yields.
        if explicit_country:
            p.error('--wifi-country is only valid for kernel builds with Wi-Fi and without --wifi-firmware-c')
        if a.wifi_regrev is not None:
            p.error('--wifi-regrev is only valid for kernel builds that download the Wi-Fi firmware')
    if a.target != 'kernel':
        if any(getattr(a, key) is not None for key in
               ('v3d', 'wifi', 'ethernet', 'storage', 'storage_validation', 'sd_base_clock_hz',
                'storage_partition', 'wifi_firmware_c', 'tls_trust_c', 'prefix', 'make')):
            p.error('kernel configuration options are only valid for kernel builds')
        build = a.build_dir or ('out/sim' if a.target == 'sim' else 'out/host')
        cmake = shutil.which('cmake')
        if not cmake:
            p.error('CMake is required for desktop builds')
        cmd = [cmake, '-S', '.', '-B', build]
        if a.target == 'sim':
            cmd.append('-DVANTAGE_BUILD_SIMULATOR=ON')
            if a.sdl:
                cmd.append('-DCMAKE_PREFIX_PATH=' + a.sdl)
        elif a.sdl:
            p.error('--sdl is only valid for sim')
        run(cmd, env)
        run([cmake, '--build', build, '--config', 'Release', '--parallel', a.jobs], env)
        if a.target == 'test':
            ctest = shutil.which('ctest')
            if not ctest:
                p.error('CTest is required for test')
            run([ctest, '--test-dir', build, '-C', 'Release', '--output-on-failure'], env)
        return
    if a.sdl:
        p.error('--sdl is only valid for sim')
    dirs = tool_dirs(a.toolchain_dir)
    dirs += tool_dirs(ROOT / '.tools')
    if os.name == 'nt' and env.get('LOCALAPPDATA'):
        dirs += tool_dirs(Path(env['LOCALAPPDATA']) / 'Temp/opencode/vantage-gnu-tools')
    path = env.get('PATH', '')
    make = a.make or env.get('MAKE') or find_tool('make', dirs, path) or find_tool('gmake', dirs, path)
    if not make:
        p.error('GNU make not found; install it or set VANTAGE_TOOLCHAIN_DIR / --make')
    prefix = a.prefix or env.get('CROSS_COMPILE')
    if not prefix:
        prefix = next((x for x in ('aarch64-linux-gnu-', 'aarch64-none-elf-')
                       if find_tool(x + 'gcc', dirs, path)), None)
    if not prefix or any(not find_tool(prefix + tool, dirs, path) for tool in ('gcc', 'ld', 'objcopy')):
        p.error('AArch64 GNU gcc, ld and objcopy not found; set VANTAGE_TOOLCHAIN_DIR or --prefix')
    if fetch:
        # A country given by option or environment must work; the automatic one may fail.
        a.wifi_firmware_c = wifi_assets(a.wifi_country, -1 if a.wifi_regrev is None else a.wifi_regrev,
                                        p.error if a.wifi_country else None)
    if a.tls_trust_c == 'none':
        a.tls_trust_c = ''
    elif not (a.tls_trust_c or env.get('TLS_TRUST_C')):
        a.tls_trust_c = tls_trust()
    env['PATH'] = os.pathsep.join([*(str(d) for d in dirs if d.is_dir()), path])
    cmd = [make, '-j' + str(a.jobs), 'BUILD_DIR=' + (a.build_dir or env.get('BUILD_DIR', 'out/pi4')),
           'CC=' + env.get('CC', prefix + 'gcc'), 'LD=' + env.get('LD', prefix + 'ld'),
           'OBJCOPY=' + env.get('OBJCOPY', prefix + 'objcopy'),
           'PYTHON=' + sys.executable.replace('\\', '/')]
    if os.name == 'nt':
        shell = find_tool('sh', dirs, path)
        if not shell:
            p.error('a POSIX sh is required by GNU make on Windows; set VANTAGE_TOOLCHAIN_DIR')
        cmd.append('SHELL=' + Path(shell).as_posix())
    for option, name in (('v3d', 'V3D'), ('wifi', 'WIFI'), ('ethernet', 'ETHERNET'), ('storage', 'STORAGE'),
                         ('storage_validation', 'STORAGE_VALIDATION'),
                         ('sd_base_clock_hz', 'SD_BASE_CLOCK_HZ'),
                         ('storage_partition', 'STORAGE_PARTITION'),
                         ('wifi_firmware_c', 'WIFI_FIRMWARE_C'), ('tls_trust_c', 'TLS_TRUST_C')):
        value = getattr(a, option)
        if value is not None:
            cmd.append(name + '=' + str(value).replace('\\', '/'))
    wifi = a.wifi if a.wifi is not None else env.get('WIFI', '1')
    status = ('disabled' if wifi == '0' else 'assets supplied' if a.wifi_firmware_c or
              env.get('WIFI_FIRMWARE_C') else 'assets unavailable; radio startup will be skipped')
    print('Wi-Fi: ' + status, flush=True)
    trust = a.tls_trust_c if a.tls_trust_c is not None else env.get('TLS_TRUST_C')
    print('TLS trust anchors: ' + ('supplied' if trust else 'none; HTTPS connections will fail with TLS_NO_TRUST'),
          flush=True)
    run(cmd, env)


if __name__ == '__main__':
    try:
        main()
    except (subprocess.CalledProcessError, OSError) as error:
        print('Build failed:', error, file=sys.stderr)
        sys.exit(1)
