"""Cache or embed the Raspberry Pi 4 BCM4345C0 RAM patch.

Review the Cypress terms with the fetch command, then use fetch --accept-license
to obtain the patch. Pass its HCD path to build.py --bluetooth 1
--bluetooth-patchram PATH. Keep the cached license with any packaged firmware.
"""
import argparse
from hashlib import sha256
from pathlib import Path
from urllib.request import urlopen


REVISION = 'adb4d55c8f193ff16ece74dd72fd6e8801632103'
BASE = f'https://raw.githubusercontent.com/RPi-Distro/bluez-firmware/{REVISION}/debian/'
NOTICE = 'copyright'
NOTICE_SHA = '79576e5ea6740845bf71ce96ad4e31cd49797c8e1a259d64670f48554b8eb67c'
LICENSE = 'LICENSE-cypress.txt'
HCD = 'BCM4345C0.hcd'
HCD_SHA = '51c45e77ddad91a19e96dc8fb75295b2087c279940df2634b23baf71b6dea42c'
MAX_BYTES = 64 * 1024


def read_bounded(stream):
    return stream.read(MAX_BYTES + 1)


def read_pin(path, digest):
    with path.open('rb') as stream:
        data = read_bounded(stream)
    if len(data) > MAX_BYTES or sha256(data).hexdigest() != digest:
        raise ValueError(f'{path} does not match Raspberry Pi firmware pin {REVISION}')
    return data


def obtain(directory, source, digest):
    path = directory / Path(source).name
    if path.is_file():
        return read_pin(path, digest)
    with urlopen(BASE + source, timeout=30) as stream:
        data = read_bounded(stream)
    if len(data) > MAX_BYTES or sha256(data).hexdigest() != digest:
        raise ValueError(f'{source} failed verification for Raspberry Pi firmware pin {REVISION}')
    path.write_bytes(data)
    return data


def fetch(directory, accepted):
    directory.mkdir(parents=True, exist_ok=True)
    notice = obtain(directory, NOTICE, NOTICE_SHA).decode()
    marker = '\nLicense: CYPRESS-WIRELESS-CONNECTIVITY-DEVICES-DRIVER-END-USER-LICENSE-AGREEMENT\n'
    license_lines = notice.rsplit(marker, 1)[1].split('\n\n', 1)[0].splitlines()
    license_path = directory / LICENSE
    license_path.write_text('\n'.join('' if line == ' .' else line[1:] for line in license_lines) + '\n',
                            encoding='utf-8')
    if not accepted:
        print(f'Review {license_path}, then use fetch --accept-license to download the patch.')
        return
    obtain(directory, 'firmware/broadcom/' + HCD, HCD_SHA)
    print(f'Patch verified at {directory / HCD}')


def embed(source, output):
    data = read_pin(source, HCD_SHA)
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open('w', encoding='utf-8', newline='\n') as stream:
        stream.write('/* Generated by tools/bluetooth_firmware.py. */\n'
                     '#include <vantage/drivers/bluetooth.h>\n\n'
                     'static const uint8_t hcd[] = {\n')
        for offset in range(0, len(data), 16):
            stream.write('    ' + ', '.join(f'0x{n:02x}' for n in data[offset:offset + 16]) + ',\n')
        stream.write('};\n\nconst BtPatch pi4_bt_patch = {hcd, sizeof(hcd)};\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='action', required=True)
    download = sub.add_parser('fetch', help='cache the pinned HCD and Cypress terms')
    download.add_argument('--dir', type=Path, default=Path('out/bluetooth-firmware'))
    download.add_argument('--accept-license', action='store_true')
    generate = sub.add_parser('embed', help='verify the explicit HCD and generate C')
    generate.add_argument('--input', type=Path, required=True)
    generate.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    try:
        if args.action == 'fetch':
            fetch(args.dir, args.accept_license)
        else:
            embed(args.input, args.output)
    except (OSError, ValueError) as error:
        parser.error(str(error))


if __name__ == '__main__':
    main()
